package com.pvknee.ui;

/**
 * The panel's spacing rhythm, in pixels.
 */
public final class Spacing
{
	/** Between blocks on a page. */
	public static final int BLOCK_GAP = 14;
	/** From a section title to the card under it. */
	public static final int TITLE_GAP = 6;
	/** Between items inside a block or a card. */
	public static final int ITEM_GAP = 4;
	/** Inside a card. */
	public static final int PADDING = 10;
	/** Corner rounding of cards and bars. */
	public static final int ARC = 8;

	private Spacing()
	{
	}
}
